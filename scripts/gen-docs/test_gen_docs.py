"""Unit tests of scripts/gen-docs.py on small workspaces.

    python3 -I -B -m unittest discover -s scripts/gen-docs -p 'test_*.py'
"""
import contextlib
import importlib.util
import io
import json
import os
import shutil
import subprocess
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = importlib.util.spec_from_file_location(
    "gen_docs", os.path.join(os.path.dirname(HERE), "gen-docs.py")
)
gen_docs = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(gen_docs)

BEGIN = "<!-- generated by scripts/gen-docs.py"
END = "<!-- end generated -->"

PROTOCOL = """\
pub const CAPABILITIES: &[(&str, Option<u16>)] = &[
    ("anchored_notes", Some(PROTOCOL_VERSION_9)),
    ("recap_since", None),
];
"""


class Workspace:
    """A temporary repository root with the two tables' source entries."""

    def __init__(self, test):
        self.dir = tempfile.TemporaryDirectory()
        test.addCleanup(self.dir.cleanup)
        self.root = self.dir.name
        self.write("src/protocol.rs", PROTOCOL)
        self.write("docs/tables/mcp-tools/langspan_status.txt", "Inspect\n")
        self.write("docs/tables/mcp-tools/langspan_admit.txt", "Request a set\n")
        self.write("docs/tables/capabilities/anchored_notes.txt", "a note's `anchor`\n")
        self.write("docs/tables/capabilities/recap_since.txt", "a recap's `since`\n")
        marked = f"{BEGIN} -->\nstale\n{END}\n"
        self.write("docs/usage/mcp.md", f"# MCP\n\nBefore.\n\n{marked}\nAfter.\n")
        self.write(gen_docs.CAPABILITY_DOC, f"# ADR\n\n{marked}\nAfter.\n")
        # 0.10.0 sorts after 0.2.0 by version, before it by name.
        self.write("fixtures/event-types/0.2.0.txt", "booted\nlanded\n")
        self.write("fixtures/event-types/0.10.0.txt", "booted\nscan_failed\n")
        self.write(gen_docs.RELEASES_DOC, f"# Retries\n\n{marked}\nAfter.\n")

    def path(self, relative):
        return os.path.join(self.root, relative)

    def write(self, relative, text):
        os.makedirs(os.path.dirname(self.path(relative)), exist_ok=True)
        with open(self.path(relative), "w", encoding="utf-8") as f:
            f.write(text)

    def read(self, relative):
        with open(self.path(relative), encoding="utf-8") as f:
            return f.read()

    def run(self, *args):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = gen_docs.main(["--root", self.root, *args])
        return code, out.getvalue() + err.getvalue()


class Tables(unittest.TestCase):
    def test_writes_rows_in_name_order_between_the_markers_only(self):
        ws = Workspace(self)
        code, _ = ws.run()
        self.assertEqual(code, 0)
        page = ws.read("docs/usage/mcp.md")
        self.assertTrue(page.startswith("# MCP\n\nBefore.\n\n" + BEGIN))
        self.assertTrue(page.endswith(END + "\n\nAfter.\n"))
        self.assertIn(
            "| Tool | Operation |\n| --- | --- |\n"
            "| `langspan_admit` | Request a set |\n"
            "| `langspan_status` | Inspect |\n",
            page,
        )
        self.assertNotIn("stale", page)

    def test_takes_since_version_from_the_protocol_source(self):
        ws = Workspace(self)
        ws.run()
        adr = ws.read(gen_docs.CAPABILITY_DOC)
        self.assertIn("| `anchored_notes` | a note's `anchor` | 9 |\n", adr)
        self.assertIn("| `recap_since` | a recap's `since` | none |\n", adr)

    def test_a_second_run_changes_nothing(self):
        ws = Workspace(self)
        ws.run()
        first = ws.read("docs/usage/mcp.md")
        ws.run()
        self.assertEqual(ws.read("docs/usage/mcp.md"), first)
        self.assertEqual(ws.run("--check")[0], 0)

    def test_check_writes_nothing_and_names_the_stale_file_and_the_fix(self):
        ws = Workspace(self)
        code, report = ws.run("--check")
        self.assertEqual(code, 1)
        self.assertIn("docs/usage/mcp.md", report)
        self.assertIn(gen_docs.CAPABILITY_DOC, report)
        self.assertIn("python3 scripts/gen-docs.py", report)
        self.assertIn("stale", ws.read("docs/usage/mcp.md"))

    def test_a_new_entry_makes_the_table_stale(self):
        ws = Workspace(self)
        ws.run()
        ws.write("docs/tables/mcp-tools/langspan_brief.txt", "Deliver\n")
        code, report = ws.run("--check")
        self.assertEqual(code, 1)
        self.assertIn("docs/usage/mcp.md", report)
        self.assertNotIn(gen_docs.CAPABILITY_DOC, report)

    def test_a_capability_without_an_entry_fails_naming_it(self):
        ws = Workspace(self)
        os.remove(ws.path("docs/tables/capabilities/recap_since.txt"))
        code, report = ws.run()
        self.assertEqual(code, 2)
        self.assertIn("recap_since", report)
        self.assertIn("stale", ws.read(gen_docs.CAPABILITY_DOC))

    def test_an_entry_without_a_capability_fails_naming_it(self):
        ws = Workspace(self)
        ws.write("docs/tables/capabilities/gone.txt", "x\n")
        code, report = ws.run("--check")
        self.assertEqual(code, 2)
        self.assertIn("gone", report)

    def test_an_entry_must_be_one_line_without_a_cell_separator(self):
        for text in ["", "two\nlines\n", "a | b\n"]:
            ws = Workspace(self)
            ws.write("docs/tables/mcp-tools/langspan_admit.txt", text)
            code, report = ws.run()
            self.assertEqual(code, 2, text)
            self.assertIn("langspan_admit.txt", report)

    def test_releases_in_version_order_with_what_each_changed(self):
        ws = Workspace(self)
        code, report = ws.run()
        self.assertEqual(code, 0, report)
        self.assertIn(
            f"{BEGIN} from fixtures/event-types/; edit those files, not this table -->\n\n"
            "| Release | Event types it reads | Change from the release before |\n"
            "| --- | --- | --- |\n"
            "| 0.2.0 | 2 | the earliest list |\n"
            "| 0.10.0 | 2 | adds `scan_failed`; drops `landed` |\n",
            ws.read(gen_docs.RELEASES_DOC),
        )

    def test_an_unchanged_release_says_so(self):
        ws = Workspace(self)
        ws.write("fixtures/event-types/0.10.1.txt", "booted\nscan_failed\n")
        ws.run()
        self.assertIn("| 0.10.1 | 2 | none |\n", ws.read(gen_docs.RELEASES_DOC))

    def test_a_changed_list_makes_the_release_table_stale(self):
        ws = Workspace(self)
        ws.run()
        ws.write("fixtures/event-types/0.10.0.txt", "booted\n")
        code, report = ws.run("--check")
        self.assertEqual(code, 1)
        self.assertIn(gen_docs.RELEASES_DOC, report)
        self.assertNotIn("docs/usage/mcp.md", report)

    def test_a_list_must_be_one_event_type_per_line(self):
        for name, text in [
            ("0.3.0.txt", ""),
            ("0.3.0.txt", "booted\n\nlanded\n"),
            ("0.3.0.txt", "Booted landed\n"),
            ("latest.txt", "booted\n"),
        ]:
            ws = Workspace(self)
            ws.write(f"fixtures/event-types/{name}", text)
            code, report = ws.run()
            self.assertEqual(code, 2, (name, text))
            self.assertIn(name, report)
            self.assertIn("stale", ws.read(gen_docs.RELEASES_DOC))

    def test_a_page_without_markers_fails(self):
        ws = Workspace(self)
        ws.write("docs/usage/mcp.md", "# MCP\n")
        code, report = ws.run("--check")
        self.assertEqual(code, 2)
        self.assertIn("docs/usage/mcp.md", report)
        self.assertIn(END, report)


class TwoPullRequests(unittest.TestCase):
    """Issue #298's "done when": two branches that each add a tool and a
    capability, and regenerate, merge without a conflict in docs. A Git test,
    since Git's merge is what is verified; it skips without `git`."""

    def git(self, *args):
        env = {
            "PATH": os.environ.get("PATH", ""),
            "HOME": self.ws.root,
            "GIT_CONFIG_GLOBAL": os.devnull,
            "GIT_CONFIG_NOSYSTEM": "1",
        }
        identity = ["-c", "user.name=t", "-c", "user.email=t@example.invalid"]
        return subprocess.run(
            ["git", *identity, *args], cwd=self.ws.root, env=env,
            capture_output=True, text=True, check=False,
        )

    def ok(self, *args):
        done = self.git(*args)
        self.assertEqual(done.returncode, 0, f"git {args}: {done.stdout}{done.stderr}")

    def add(self, tool, capability):
        """What a pull request does: an entry each, a CAPABILITIES line in
        name order, then the generator."""
        self.ws.write(f"docs/tables/mcp-tools/{tool}.txt", f"{tool} text\n")
        self.ws.write(f"docs/tables/capabilities/{capability}.txt", "fields\n")
        lines = self.ws.read("src/protocol.rs").splitlines(keepends=True)
        rows = sorted([*lines[1:-1], f'    ("{capability}", None),\n'])
        self.ws.write("src/protocol.rs", "".join([lines[0], *rows, lines[-1]]))
        self.assertEqual(self.ws.run()[0], 0)

    def test_two_branches_adding_items_merge_cleanly(self):
        if shutil.which("git") is None:
            self.skipTest("skipped: git is not on PATH")
        self.ws = Workspace(self)
        # One unchanged row between the two additions in each table, as when
        # an existing name sorts between the two new ones.
        self.ws.write("docs/tables/mcp-tools/langspan_map.txt", "Map\n")
        self.ws.write("docs/tables/capabilities/renames.txt", "r\n")
        self.ws.write("src/protocol.rs", PROTOCOL.replace("];", '    ("renames", None),\n];'))
        self.assertEqual(self.ws.run()[0], 0)
        self.ok("init", "-q", "-b", "main")
        self.ok("add", "-A")
        self.ok("commit", "-qm", "base")
        for branch, tool, capability in [
            ("a", "langspan_brief", "briefing_memory"),
            ("b", "langspan_today", "trails"),
        ]:
            self.ok("switch", "-q", "-c", branch, "main")
            self.add(tool, capability)
            self.ok("add", "-A")
            self.ok("commit", "-qm", branch)
        self.ok("switch", "-q", "a")
        self.ok("merge", "-q", "--no-edit", "b")
        self.assertEqual(self.ws.run("--check"), (0, ""))
        page = self.ws.read("docs/usage/mcp.md")
        self.assertIn("| `langspan_brief` | langspan_brief text |\n", page)
        self.assertIn("| `langspan_today` | langspan_today text |\n", page)
        adr = self.ws.read(gen_docs.CAPABILITY_DOC)
        self.assertIn("| `briefing_memory` | fields | none |\n", adr)
        self.assertIn("| `trails` | fields | none |\n", adr)


def issue(number, title, area, body):
    labels = [{"name": "roadmap"}] + ([{"name": f"area: {area}"}] if area else [])
    return {
        "number": number,
        "title": title,
        "url": f"https://github.com/o/r/issues/{number}",
        "labels": labels,
        "body": body,
    }


ROADMAP = f"""\
# Roadmap

Intro.

{BEGIN} -->
## B. Write coordination

- [B9: Old](https://github.com/o/r/issues/28): kept status text. Built; a run remains.

{END}

## Not building

Tail.
"""


class Roadmap(unittest.TestCase):
    def setUp(self):
        self.ws = Workspace(self)
        self.ws.write("docs/roadmap.md", ROADMAP)
        problem = "**Decision:** x.\n\n**Problem.** First sentence here. Second.\n"
        issues = [
            issue(29, "B10: Renames", "B Write coordination", problem),
            issue(28, "B9: Alert a write", "B Write coordination", problem),
            issue(16, "A11: Outline", "A Hosts and hook events",
                  "**Index.** Said in the\nissue itself.\n\n" + problem),
            issue(99, "No ID here", "A Hosts and hook events", problem),
            issue(12, "A4: Cursor", "A Hosts and hook events", problem),
        ]
        self.issues = self.ws.path("issues.json")
        with open(self.issues, "w", encoding="utf-8") as f:
            json.dump(issues, f)

    def test_sections_by_area_items_by_id_then_number(self):
        code, report = self.ws.run("--roadmap", self.issues, "--date", "27 November 2026")
        self.assertEqual(code, 0, report)
        page = self.ws.read("docs/roadmap.md")
        url = "https://github.com/o/r/issues/"
        self.assertIn(
            f"{BEGIN} --roadmap from the open `roadmap` issues on 27 November 2026; "
            "change an issue, not this list -->\n\n"
            "## A. Hosts and hook events\n\n"
            f"- [A4: Cursor]({url}12): First sentence here.\n"
            f"- [A11: Outline]({url}16): Said in the issue itself.\n"
            f"- [No ID here]({url}99): First sentence here.\n\n"
            "## B. Write coordination\n\n"
            f"- [B9: Alert a write]({url}28): kept status text. Built; a run remains.\n"
            f"- [B10: Renames]({url}29): First sentence here.\n\n"
            f"{END}\n\n## Not building\n\nTail.\n",
            page,
        )
        self.assertTrue(page.startswith("# Roadmap\n\nIntro.\n\n"))
        # A summary taken from the Problem paragraph is named, so its issue
        # can be given an Index line.
        self.assertIn("#12", report)
        self.assertNotIn("#28", report)

    def test_an_issue_without_an_area_fails_and_writes_nothing(self):
        with open(self.issues, encoding="utf-8") as f:
            issues = json.load(f)
        issues.append(issue(5, "Z1: Lost", None, "**Problem.** P.\n"))
        with open(self.issues, "w", encoding="utf-8") as f:
            json.dump(issues, f)
        code, report = self.ws.run("--roadmap", self.issues, "--date", "1 May 2027")
        self.assertEqual(code, 2)
        self.assertIn("#5", report)
        self.assertEqual(self.ws.read("docs/roadmap.md"), ROADMAP)

    def test_check_does_not_read_the_roadmap(self):
        self.ws.run()
        self.ws.write("docs/roadmap.md", "# No markers\n")
        self.assertEqual(self.ws.run("--check")[0], 0)


if __name__ == "__main__":
    unittest.main()
