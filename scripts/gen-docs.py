#!/usr/bin/env python3
"""Generate the shared docs tables, so pull requests that add items don't
edit the same lines (issue #298).

    python3 scripts/gen-docs.py            rewrite the generated tables
    python3 scripts/gen-docs.py --check    exit 1 if one is out of date
    python3 scripts/gen-docs.py --roadmap ISSUES.json [--date "1 May 2027"]

Each table is the region between a `<!-- generated by scripts/gen-docs.py`
line and `<!-- end generated -->` in its page, built from one source entry
per row:

- docs/usage/mcp.md: the MCP tool table, from docs/tables/mcp-tools/<tool>.txt.
- ADR 0037: the capability table, from docs/tables/capabilities/<name>.txt,
  with "Since version" read from CAPABILITIES in src/protocol.rs.
- docs/usage/retries-and-recovery.md: the event types each served release
  reads, from fixtures/event-types/<release>.txt (issue #411).

--roadmap rewrites the A to J index of docs/roadmap.md from the output of
`gh issue list --label roadmap --state open --limit 500 --json
number,title,body,labels,url`. It is run on demand; CI never needs the
network. Each line's summary is the issue's `**Index.**` paragraph, else
the summary the index already gives that issue, else the first sentence of
its `**Problem.**` paragraph.

Standard library only, Python 3.9 or later. Exit 0 done, 1 stale (--check),
2 a source entry or page that can't be used.
"""
import argparse
import datetime
import json
import os
import re
import sys

MCP_DOC = "docs/usage/mcp.md"
CAPABILITY_DOC = "docs/adr/0037-protocol-capabilities.md"
ROADMAP_DOC = "docs/roadmap.md"
RELEASES_DOC = "docs/usage/retries-and-recovery.md"
TOOLS_DIR = "docs/tables/mcp-tools"
CAPABILITIES_DIR = "docs/tables/capabilities"
EVENT_TYPES_DIR = "fixtures/event-types"
PROTOCOL = "src/protocol.rs"

BEGIN = "<!-- generated by scripts/gen-docs.py"
END = "<!-- end generated -->"
FIX = "python3 scripts/gen-docs.py"

RELEASE_FILE = re.compile(r"^(\d+)\.(\d+)\.(\d+)\.txt$")
EVENT_TYPE = re.compile(r"^[a-z][a-z0-9_]*$")
CAPABILITY_LINE = re.compile(r'^\s*\("(\w+)", (?:None|Some\(PROTOCOL_VERSION_(\d+)\))\),\s*$')
ITEM_ID = re.compile(r"^([A-Z])(\d+): ")
AREA = re.compile(r"^area: ([A-Z]) (.+)$")
INDEXED = re.compile(r"\]\(https://\S+?/issues/(\d+)\): (.*)$")


class Unusable(Exception):
    """A source entry or page the generator can't use; exit 2."""


def read(root, relative):
    with open(os.path.join(root, relative), encoding="utf-8") as f:
        return f.read()


def entries(root, directory):
    """{name: cell} from one `<name>.txt` file per row, each a single line."""
    found = {}
    for file in sorted(os.listdir(os.path.join(root, directory))):
        if not file.endswith(".txt"):
            continue
        relative = f"{directory}/{file}"
        cell = read(root, relative).strip()
        if not cell or "\n" in cell or "|" in cell:
            raise Unusable(f"{relative}: write the row's text as one non-empty line without '|'")
        found[file[: -len(".txt")]] = cell
    return found


def capabilities(root):
    """{name: since} from the CAPABILITIES array, its one owner."""
    text = read(root, PROTOCOL)
    start = text.find("pub const CAPABILITIES")
    end = text.find("];", start)
    if start < 0 or end < 0:
        raise Unusable(f"{PROTOCOL}: no `pub const CAPABILITIES` array")
    found = {}
    for line in text[start:end].splitlines()[1:]:
        match = CAPABILITY_LINE.match(line)
        if not match:
            raise Unusable(f"{PROTOCOL}: can't read the CAPABILITIES line {line.strip()!r}")
        found[match.group(1)] = match.group(2) or "none"
    return found


def mcp_table(root):
    rows = [f"| `{name}` | {cell} |" for name, cell in sorted(entries(root, TOOLS_DIR).items())]
    return ["| Tool | Operation |", "| --- | --- |", *rows]


def capability_table(root):
    cells = entries(root, CAPABILITIES_DIR)
    since = capabilities(root)
    missing = sorted(since.keys() - cells.keys())
    if missing:
        raise Unusable(f"capability {missing[0]} has no {CAPABILITIES_DIR}/{missing[0]}.txt; write the fields it gates there")
    extra = sorted(cells.keys() - since.keys())
    if extra:
        raise Unusable(f"{CAPABILITIES_DIR}/{extra[0]}.txt names no capability in {PROTOCOL}; remove it")
    rows = [f"| `{name}` | {cells[name]} | {since[name]} |" for name in sorted(cells)]
    return ["| Capability | Fields it gates | Since version |", "| --- | --- | --- |", *rows]


def release_table(root):
    """One row per frozen list, in version order, with what changed from
    the release before."""
    releases = []
    for file in os.listdir(os.path.join(root, EVENT_TYPES_DIR)):
        relative = f"{EVENT_TYPES_DIR}/{file}"
        version = RELEASE_FILE.match(file)
        if not version:
            raise Unusable(f"{relative}: name a frozen list after its release, as 0.8.0.txt")
        names = read(root, relative).split("\n")
        if names[-1] != "" or not all(EVENT_TYPE.match(name) for name in names[:-1]) or len(names) < 2:
            raise Unusable(f"{relative}: write one event type per line, each ending in a newline")
        releases.append((tuple(map(int, version.groups())), file[: -len(".txt")], set(names[:-1])))
    rows, before = [], None
    for _, release, types in sorted(releases):
        if before is None:
            change = "the earliest list"
        else:
            parts = [
                f"{verb} " + ", ".join(f"`{name}`" for name in sorted(names))
                for verb, names in [("adds", types - before), ("drops", before - types)]
                if names
            ]
            change = "; ".join(parts) or "none"
        rows.append(f"| {release} | {len(types)} | {change} |")
        before = types
    return ["| Release | Event types it reads | Change from the release before |", "| --- | --- | --- |", *rows]


def regions(page, relative):
    """The page split around its generated region: (before, inside, after)."""
    lines = page.split("\n")
    begin = [i for i, line in enumerate(lines) if line.startswith(BEGIN)]
    end = [i for i, line in enumerate(lines) if line == END]
    if len(begin) != 1 or len(end) != 1 or end[0] < begin[0]:
        raise Unusable(f"{relative}: needs one line starting {BEGIN!r} and, after it, one {END!r}")
    return lines[: begin[0]], lines[begin[0] + 1 : end[0]], lines[end[0] + 1 :]


def replace(page, relative, header, body):
    before, _, after = regions(page, relative)
    return "\n".join([*before, header, "", *body, "", END, *after])


def tables(root):
    """{page: new text} for the tables CI checks."""
    built = {}
    for relative, source, body in [
        (MCP_DOC, TOOLS_DIR, mcp_table(root)),
        (CAPABILITY_DOC, CAPABILITIES_DIR, capability_table(root)),
        (RELEASES_DOC, EVENT_TYPES_DIR, release_table(root)),
    ]:
        header = f"{BEGIN} from {source}/; edit those files, not this table -->"
        built[relative] = replace(read(root, relative), relative, header, body)
    return built


def summary(issue, indexed, warnings):
    body = issue.get("body") or ""
    found = re.search(r"^\*\*Index\.\*\*\s*(.+?)(?:\n\s*\n|\Z)", body, re.M | re.S)
    if found:
        return " ".join(found.group(1).split())
    if issue["number"] in indexed:
        return indexed[issue["number"]]
    found = re.search(r"^\*\*Problem\.\*\*\s*(.+?)(?:\n\s*\n|\Z)", body, re.M | re.S)
    if not found:
        raise Unusable(f"issue #{issue['number']} has neither an **Index.** nor a **Problem.** paragraph")
    problem = " ".join(found.group(1).split())
    first = re.match(r"(.+?[.!?])(?:\s|$)", problem)
    warnings.append(f"issue #{issue['number']}: summary taken from its Problem; give it an **Index.** paragraph")
    return first.group(1) if first else problem


def roadmap(root, issues, date):
    page = read(root, ROADMAP_DOC)
    _, inside, _ = regions(page, ROADMAP_DOC)
    indexed = {}
    for line in inside:
        found = INDEXED.search(line)
        if found:
            indexed[int(found.group(1))] = found.group(2)
    areas, warnings = {}, []
    for issue in issues:
        area = [m for m in (AREA.match(label["name"]) for label in issue["labels"]) if m]
        if len(area) != 1:
            raise Unusable(f"issue #{issue['number']} needs exactly one `area: X Name` label")
        item = ITEM_ID.match(issue["title"])
        order = (0, item.group(1), int(item.group(2))) if item else (1, "", issue["number"])
        line = f"- [{issue['title']}]({issue['url']}): {summary(issue, indexed, warnings)}"
        areas.setdefault(area[0].groups(), []).append((order, line))
    body = []
    for (letter, name), items in sorted(areas.items()):
        body += [f"## {letter}. {name}", "", *(line for _, line in sorted(items)), ""]
    header = f"{BEGIN} --roadmap from the open `roadmap` issues on {date}; change an issue, not this list -->"
    return replace(page, ROADMAP_DOC, header, body[:-1]), warnings


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if a table is stale")
    parser.add_argument("--roadmap", metavar="ISSUES.json", help="rewrite the roadmap index from gh's issue list")
    parser.add_argument("--date", help="the date the index names (default: today)")
    args = parser.parse_args(argv)
    try:
        if args.roadmap:
            with open(args.roadmap, encoding="utf-8") as f:
                issues = json.load(f)
            today = datetime.date.today()
            date = args.date or f"{today.day} {today:%B %Y}"
            text, warnings = roadmap(args.root, issues, date)
            built = {ROADMAP_DOC: text}
            for warning in warnings:
                print(f"gen-docs: {warning}", file=sys.stderr)
        else:
            built = tables(args.root)
    except (Unusable, OSError, ValueError, KeyError) as problem:
        print(f"gen-docs: {problem}", file=sys.stderr)
        return 2
    stale = [relative for relative, text in built.items() if read(args.root, relative) != text]
    if args.check:
        for relative in stale:
            print(f"gen-docs: {relative} is out of date; run `{FIX}` and commit the result", file=sys.stderr)
        return 1 if stale else 0
    for relative in stale:
        with open(os.path.join(args.root, relative), "w", encoding="utf-8") as f:
            f.write(built[relative])
        print(f"gen-docs: wrote {relative}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
